function buildSuit(suit: Suit, defs: MinorDef[], idStart: number): TarotCard[] {
  const info = SUIT_INFO[suit]
  return defs.map((d, i) => {
    const rankName = RANK_NAMES[d.rank]
    const numStr = String(d.rank).padStart(2, '0')
    return {
      id: idStart + i,
      slug: `${suit}-${numStr}`,
      name: `${rankName.en} of ${suit[0].toUpperCase() + suit.slice(1)}`,
      nameKo: `${info.nameKoSuit} ${rankName.ko}`,
      arcana: 'minor',
      suit,
      number: d.rank,
      keywords: { upright: d.upright, reversed: d.reversed },
      meaning: { upright: d.meaningUpright, reversed: d.meaningReversed },
      description: d.description,
    }
  })
}

